# Regenerates sw-files.js: the list of files the service worker caches, plus a build stamp that changes
# whenever any of them changes (the stamp names the cache, so a new build replaces the old one).
# Run after editing any app file:  & ./tools/sw-files.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Push-Location $root
try {
  $files = @('index.html', 'manifest.webmanifest')
  $files += Get-ChildItem -Path css -Filter *.css -File | Sort-Object Name | ForEach-Object { "css/$($_.Name)" }
  $files += Get-ChildItem -Path src -Recurse -Filter *.js -File | ForEach-Object {
    $_.FullName.Substring($root.Length + 1).Replace('\', '/')
  } | Sort-Object
  $files += Get-ChildItem -Path icons -Filter *.png -File | Sort-Object Name | ForEach-Object { "icons/$($_.Name)" }

  $sha = [System.Security.Cryptography.SHA256]::Create()
  $lines = foreach ($f in $files) {
    $bytes = [System.IO.File]::ReadAllBytes((Join-Path $root $f))
    $hex = -join ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString('x2') })
    "${f}:$hex"
  }
  $joined = [System.Text.Encoding]::UTF8.GetBytes(($lines -join "`n"))
  $build = (-join ($sha.ComputeHash($joined) | ForEach-Object { $_.ToString('x2') })).Substring(0, 12)

  $list = (@('./') + ($files | ForEach-Object { "./$_" }) | ForEach-Object { "  '$_'," }) -join "`n"
  $js = "// Generated by tools/sw-files.ps1. Do not edit by hand.`nself.COACH_BUILD = '$build';`nself.COACH_FILES = [`n$list`n];`n"
  $utf8 = New-Object System.Text.UTF8Encoding($false)
  [System.IO.File]::WriteAllText((Join-Path $root 'sw-files.js'), $js, $utf8)
  # Stamp sw.js itself so the worker file changes byte-for-byte with each build.
  $swPath = Join-Path $root 'sw.js'
  $sw = [System.IO.File]::ReadAllText($swPath)
  $sw = [regex]::Replace($sw, '(?m)^// build [0-9a-f]{12}$', "// build $build")
  [System.IO.File]::WriteAllText($swPath, $sw, $utf8)
  Write-Output "sw-files.js: $($files.Count) files, build $build"
} finally {
  Pop-Location
}
